/* Run with Node; also supports macOS JavaScriptCore for local verification. */
(function(){
 'use strict';
 const isNode=typeof require==='function';
 if(!isNode)load('custom/model.js');
 const M=isNode?require('../custom/model.js'):globalThis.TariffModel;
 const say=isNode?console.log:print;
 let count=0;
 function check(ok,label){if(!ok)throw Error(label);count++;}
 const source={id:'mobile:jiangsu',carrier:'mobile',region:'jiangsu',name:'江苏移动'};
 check(M.price('0元/月','', 'mobile')===0,'explicit zero month');
 check(M.price('59.90','元/月','unicom')===59.9,'decimal monthly price');
 for(const p of ['','免费','20元/月优惠','20元/月减免','10元/GB','120元/年','29元起','10至30元/月','10/20元/月'])check(M.price(p,'','mobile')===null,'not a monthly base fee: '+p);
 check(M.price('59','','unicom')===null,'bare fee without unit is unknown');
 const a=M.normalize({name:'移动59元套餐',fields:{'资费标准':'59元/月','资费类型':'套餐','适用范围':'限江苏地区'}},source,0);
 check(a.monthly===59 && a.search.includes('江苏'),'mobile normalization');
 const b=M.normalize({id:'b',title:'联通套餐',fee:'9.9',firstLevel:'套餐',detail:{feeUnit:'元/月',commonData:'30',dataUnit:'GB',minute:'100'}},{id:'unicom:jiangsu',carrier:'unicom',region:'jiangsu',name:'江苏联通'},0);
 check(b.details.some(x=>x[0]==='通用流量'&&x[1]==='30 GB'),'preserve traffic unit');
 check(b.details.some(x=>x[0]==='国内通话'&&x[1]==='100 分钟'),'preserve voice unit');
 const unknown=M.normalize({id:'u',title:'年包',fee:'120',detail:{feeUnit:'元/年'}},source,1);
 check(M.filter([a,b,unknown],{min:'0',max:'20'},new Set()).length===1,'budget excludes unknown and annual fees');
 check(M.filter([a,b],{q:'限江苏地区'},new Set())[0]===a,'full text condition');
 check(M.filter([a,b],{q:'限江苏地区',nameOnly:true},new Set()).length===0,'name only');
 check(M.filter([a,b],{favOnly:true},new Set([b.key]))[0]===b,'favorite identity');
 check(M.sort([unknown,a,b],'priceDesc').map(x=>x.key).join() === [a,b,unknown].map(x=>x.key).join(),'unknown price sorted last');
 const sh=M.normalize({id:'sh',title:'上海套餐',fee:'19',firstLevel:'套餐',detail:{feeUnit:'元/月'}},{id:'unicom:shanghai',carrier:'unicom',region:'shanghai',name:'上海联通'},0);
 const national=M.normalize({id:'nation',title:'江苏可用的全国套餐',detail:{useScope:'江苏用户'}},{id:'telecom:quanguo',carrier:'telecom',region:'quanguo',name:'全国电信'},0);
 check(M.filter([a,b,sh,national],{region:'jiangsu'},new Set()).map(x=>x.key).join()===[a,b].map(x=>x.key).join(),'province filter uses snapshot region across carriers');
 check(M.filter([a,b,sh,national],{region:'jiangsu',carrier:'unicom',max:'20'},new Set())[0]===b,'province combines with carrier and price');
 check(M.filter([a,b,sh,national],{region:'quanguo'},new Set())[0]===national,'national tariffs have an explicit separate option');
 check(M.filter([a,b,sh,national],{region:''},new Set()).length===4,'clear province restores every source');
 const asOf='2026-11-04';
 const sale=(fields,firstLevel)=>M.saleState({detail:fields,firstLevel},asOf);
 check(sale({offDate:'2029-12-31'},'停售套餐').value==='stopped','official discontinued category overrides future placeholder end date');
 check(sale({offDate:'2026-11-03'},'加装包').value==='stopped','expired add-on is discontinued even without stopped category');
 check(sale({offDate:'2026-11-04'},'套餐').value==='onsale','end date remains active throughout Beijing calendar day');
 check(sale({onDate:'2026-11-05',offDate:'2027-12-31'},'套餐').value==='upcoming','future launch is not on sale');
 check(M.saleState({fields:{'上线日期':'2026年1月1日','下线日期':'2026年10月31日'}},asOf).value==='stopped','mobile Chinese end date');
 check(sale({onDate:'20260101',offDate:'20271231'}).value==='onsale','compact official dates');
 check(sale({state:'已停售',offDate:'2029-12-31'}).value==='stopped','explicit stopped status');
 check(sale({state:'在售'}).value==='onsale','explicit on-sale status');
 check(sale({offDate:'2026-02-30'}).value==='unknown','invalid calendar date stays unknown');
 check(sale({validPeriod:'2026年10月31日前办理优惠'}).value==='unknown','contract conditions do not imply sale status');
 check(sale({onDate:'2026-01-01',offDate:'长期有效'}).value==='onsale','explicit perpetual validity');
 check(M.saleState({title:'停售提示业务',detail:{}},asOf).value==='unknown','title keyword does not classify status');
 check(M.saleState({manual:true,saleStatus:'stopped'},asOf).value==='stopped','custom record uses user-declared sale status');
 check(M.saleState({manual:true},asOf).value==='unknown','legacy custom record stays unknown');
 check(M.dateDay('2026/11/4')==='2026-11-04','unpadded date parsing');
 const active=M.normalize({id:'active',title:'在售测试',fee:'9元/月',detail:{state:'在售'}},source,0);
 const stopped=M.normalize({id:'stopped',title:'停售测试',fee:'19元/月',firstLevel:'停售套餐',detail:{offDate:'2029-12-31'}},source,1);
 check(stopped.saleStatus==='stopped'&&stopped.details.some(x=>x[0]==='销售状态'&&x[1]==='停售业务'),'normalized status is visible in detail');
 check(M.filter([active,stopped,unknown],{saleStatus:'onsale'},new Set())[0]===active,'on-sale filter excludes discontinued and unknown');
 check(M.filter([active,stopped,unknown],{saleStatus:'stopped',region:'jiangsu',carrier:'mobile',max:'20'},new Set())[0]===stopped,'stopped filter combines with province carrier and budget');
 check(M.filter([active,stopped,unknown],{saleStatus:'unknown'},new Set())[0]===unknown,'unknown status is separately selectable');
 check(M.filter([active,stopped,unknown],{saleStatus:''},new Set()).length===3,'clear sale status restores all records');
 const alpha={...sh,title:'A plan',label:'上海联通'},zulu={...a,title:'Z plan',label:'江苏移动'};
 check(M.sort([zulu,alpha],'name')[0]===alpha,'name sorting is independent of region');
 check(new Set(M.defaults).size===12,'12 requested sources');
 check(M.escape('<img src=x onerror=1>').includes('&lt;img'),'HTML escape');
 check(M.csvCell('=HYPERLINK("evil")').startsWith('"\''),'CSV formula protection');
 if(isNode){
  check(M.safeURL('javascript:alert(1)')==='','reject executable URLs');
  check(M.safeURL('https://www.189.cn/')==='https://www.189.cn/','allow official HTTPS');
 }
 say('Personal data model: '+count+' checks passed');
})();
